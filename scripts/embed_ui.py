"""PlatformIO pre-script: embed the web app in device-ui/ into a generated C++
header (ui_files.h) holding gzip-compressed (where useful) byte arrays.

All logic is in pure functions so tests can import this module; the PlatformIO
part runs only under SCons and is a no-op on the native env."""
import gzip
import hashlib
from pathlib import Path

MAX_TOTAL_BYTES = 600 * 1024
EXCLUDED_TOP_DIRS = {"mock", "tests", "tools"}
# Allow-list: only these extensions are embedded (anything else, e.g. package.json, *.txt,
# *.md, licence files, stays out). Value: (MIME type, gzip?). Fonts and images are already
# compressed, so they are stored as-is.
MIME = {
    ".html": ("text/html; charset=utf-8", True),
    ".css": ("text/css", True),
    ".js": ("text/javascript", True),  # ES modules refuse to load under other types
    ".svg": ("image/svg+xml", True),
    ".woff2": ("font/woff2", False),
    ".png": ("image/png", False),
    ".ico": ("image/x-icon", False),
}
DEFAULT_MIME = ("application/octet-stream", False)


def embeddable(path):
    """True if the file's extension is on the allow-list."""
    return Path(path).suffix.lower() in MIME


class EmbedError(Exception):
    """Raised for input that must fail the build with a clear message."""


def mime_for(path):
    """Return (mime type, gzip?) for a path, by extension."""
    return MIME.get(Path(path).suffix.lower(), DEFAULT_MIME)


def collect(root):
    """Return [(relative posix path, bytes)] sorted by path; missing root is empty."""
    root = Path(root)
    if not root.is_dir():
        return []
    found = []
    for path in root.rglob("*"):
        rel = path.relative_to(root)
        if not path.is_file() or not embeddable(path):
            continue
        if any(part.startswith(".") for part in rel.parts) or rel.parts[0] in EXCLUDED_TOP_DIRS:
            continue
        if "secret" in rel.as_posix().lower():
            raise EmbedError(f"refusing to embed '{rel.as_posix()}': path contains 'secret'")
        found.append((rel.as_posix(), path.read_bytes()))
    return sorted(found, key=lambda item: item[0])


def c_string(text):
    """Quote text as a C string literal; reject characters we will not escape."""
    if any(ord(ch) < 0x20 or ord(ch) > 0x7E for ch in text):
        raise EmbedError(f"unsupported character in {text!r}")
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def embedded_bytes(rel_path, data):
    """Return (payload, mime, gzip?) as it will be stored in the header."""
    mime, compress = mime_for(rel_path)
    return (gzip.compress(data, compresslevel=9, mtime=0) if compress else data), mime, compress


def byte_array(name, payload):
    lines = []
    for i in range(0, len(payload), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in payload[i:i + 16]) + ",")
    body = "\n".join(lines) if lines else "    0x00,"
    return f"static const uint8_t {name}[] = {{\n{body}\n}};\n"


def content_tag(entries):
    """16 hex digits identifying the whole embedded set; the firmware builds ETags from it, so
    any change to any file makes browsers fetch the app again after a firmware update."""
    digest = hashlib.sha256()
    for path, payload, mime, _ in entries:
        digest.update(f"{path}\0{mime}\0{len(payload)}\0".encode())
        digest.update(payload)
    return digest.hexdigest()[:16]


def render(files):
    """Render the full header text for [(rel path, bytes)]."""
    entries = [(f"/{rel}", *embedded_bytes(rel, data)) for rel, data in files]
    total = sum(len(payload) for _, payload, _, _ in entries)
    if total > MAX_TOTAL_BYTES:
        raise EmbedError(f"embedded UI is {total} bytes, over the limit of {MAX_TOTAL_BYTES} bytes")
    out = [
        "// Generated by scripts/embed_ui.py from device-ui/. Do not edit.",
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "struct UiFile { const char* path; const char* mime; const uint8_t* data; size_t len; bool gzip; };",
        "",
    ]
    for i, (_, payload, _, _) in enumerate(entries):
        out.append(byte_array(f"UI_DATA_{i}", payload))
    if entries:
        rows = [f"    {{{c_string(path)}, {c_string(mime)}, UI_DATA_{i}, {len(payload)}, "
                f"{'true' if gz else 'false'}}},"
                for i, (path, payload, mime, gz) in enumerate(entries)]
        out.append("static const UiFile UI_FILES[] = {\n" + "\n".join(rows) + "\n};")
    else:
        out.append("static const UiFile UI_FILES[1] = {{nullptr, nullptr, nullptr, 0, false}};")
    out.append(f"static const size_t UI_FILE_COUNT = {len(entries)};")
    out.append(f"static const size_t UI_TOTAL_BYTES = {total};")
    out.append(f'static const char UI_ETAG[] = "{content_tag(entries)}";')
    return "\n".join(out) + "\n"


def build(root, out_path):
    """Generate the header; return (file count, embedded bytes, changed?)."""
    from config.core import write_if_changed
    files = collect(root)
    text = render(files)
    total = sum(len(embedded_bytes(rel, data)[0]) for rel, data in files)
    return len(files), total, write_if_changed(out_path, text)


def main(env):
    import sys
    project_dir = Path(env.subst("$PROJECT_DIR"))
    sys.path.insert(0, str(project_dir / "scripts"))
    out_dir = Path(env.subst("$BUILD_DIR")) / "generated"
    try:
        count, total, changed = build(project_dir / "device-ui", out_dir / "ui_files.h")
    except (OSError, EmbedError) as exc:
        raise SystemExit(f"embed_ui: {exc}") from exc
    env.Append(CPPPATH=[str(out_dir)])
    print(f"embed_ui: {count} files, {total} bytes ({'updated' if changed else 'unchanged'})")


try:
    Import("env")  # noqa: F821 -- provided by PlatformIO/SCons
except NameError:
    env = None
if env is not None and env["PIOPLATFORM"] != "native":
    main(env)
