// Generates device-ui/js/tz.js from the system tz database.
// Usage: node device-ui/tools/make_tz.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const ZONEINFO = '/usr/share/zoneinfo';
const OUT = new URL('../js/tz.js', import.meta.url);
const MAX_POSIX = 47;

const zones = new Set(['UTC']);
for (const line of readFileSync(`${ZONEINFO}/zone.tab`, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const name = line.split('\t')[2];
  if (name) zones.add(name);
}

// POSIX TZ string = last non-empty line of the TZif file (".../\n<POSIX>\n").
function posixOf(file) {
  const buf = readFileSync(file);
  if (buf.length < 2 || buf[buf.length - 1] !== 0x0a) return '';
  const end = buf.length - 1;
  const start = buf.lastIndexOf(0x0a, end - 1) + 1;
  return buf.subarray(start, end).toString('latin1');
}

const table = {};
for (const zone of [...zones].sort()) {
  const file = `${ZONEINFO}/${zone}`;
  if (!existsSync(file)) {
    process.stderr.write(`warning: missing zone file, skipped: ${zone}\n`);
    continue;
  }
  const posix = posixOf(file);
  if (posix === '' || Buffer.byteLength(posix, 'latin1') > MAX_POSIX) {
    process.stderr.write(`warning: bad POSIX string, skipped: ${zone} (${JSON.stringify(posix)})\n`);
    continue;
  }
  table[zone] = posix;
}

const versionLine = readFileSync(`${ZONEINFO}/tzdata.zi`, 'latin1').split('\n', 1)[0];
const version = /^# version (\S+)/.exec(versionLine)?.[1];
const names = Object.keys(table);

// Pack several "zone":"posix" pairs per line, at most ~110 chars per line.
const lines = [];
let cur = '  ';
for (const name of names) {
  const pair = `${JSON.stringify(name)}: ${JSON.stringify(table[name])},`;
  if (cur.trim() !== '' && cur.length + pair.length + 1 > 110) {
    lines.push(cur.trimEnd());
    cur = '  ';
  }
  cur += pair + ' ';
}
if (cur.trim() !== '') lines.push(cur.trimEnd());

const header = [
  '// Generated by tools/make_tz.mjs from the system tz database' +
    (version ? ` (tzdata ${version})` : '') + '. Do not edit.',
  '// Maps IANA zone names to POSIX TZ strings.',
  '',
].join('\n');

const body = `const RAW = {\n${lines.join('\n')}\n};

export const TZ = Object.freeze(RAW);

export function posixFor(iana) {
  return typeof iana === 'string' && Object.hasOwn(TZ, iana) ? TZ[iana] : null;
}

export function zoneNames() {
  return Object.keys(TZ).sort();
}

export function browserZone() {
  try {
    const zone = Intl.DateTimeFormat().resolvedOptions().timeZone;
    return Object.hasOwn(TZ, zone) ? zone : null;
  } catch {
    return null;
  }
}
`;

writeFileSync(OUT, header + body);
process.stdout.write(`wrote ${names.length} zones to ${OUT.pathname}\n`);
